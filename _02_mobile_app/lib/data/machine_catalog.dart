Machine _machine({
  required String id,
  required String name,
  required String type,
  required String code,
  required String location,
  required String imagePath,
  required MachineStatus status,
  required int efficiency,
  required double temperature,
  required double speed,
  required double vibration,
  required double power,
  required double pressure,
  required int productionCount,
  required double productionRate,
  required String? activeAlert,
  required DateTime lastUpdated,
  required Color color,
}) {
  final series = <double>[85, 88, 92, 89, 94, 91, 93, efficiency.toDouble()]
      .asMap()
      .entries
      .map((e) => MachineMetricPoint(label: '10:${(e.key * 15).toString().padLeft(2, '0')}', value: e.value))
      .toList(growable: false);

  return Machine(
    id: id,
    name: name,
    type: type,
    code: code,
    location: location,
    imagePath: imagePath,
    status: status,
    efficiency: efficiency,
    temperature: temperature,
    speed: speed,
    vibration: vibration,
    power: power,
    pressure: pressure,
    productionCount: productionCount,
    productionRate: productionRate,
    activeAlert: activeAlert,
    lastUpdated: lastUpdated,
    performanceSeries: series,
    sensors: [
      MachineSensor(label: 'Vibration', unit: 'mm/s', value: vibration, color: DT.green),
      MachineSensor(label: 'Noise Level', unit: 'dB', value: 74 + vibration * 10, color: DT.blue),
      MachineSensor(label: 'Oil Pressure', unit: 'PSI', value: pressure, color: DT.cyan),
      const MachineSensor(label: 'Coolant Level', unit: '%', value: 87, color: DT.green),
      const MachineSensor(label: 'Belt Tension', unit: '%', value: 92, color: DT.green),
      MachineSensor(label: 'Spindle Load', unit: '%', value: (efficiency * 0.7).clamp(10, 99).toDouble(), color: DT.yellow),
    ],
    timeline: [
      MachineTimelineEvent(time: lastUpdated.subtract(const Duration(hours: 2)), title: 'Production target synced', detail: 'Daily output target updated from factory dashboard.', color: DT.cyan),
      MachineTimelineEvent(time: lastUpdated.subtract(const Duration(minutes: 45)), title: 'Sensor heartbeat normal', detail: 'All configured sensors reporting within threshold.', color: DT.green),
      MachineTimelineEvent(time: lastUpdated, title: status == MachineStatus.fault ? 'Critical fault detected' : 'Live data refreshed', detail: activeAlert ?? 'Machine metrics refreshed successfully.', color: color),
    ],
  );
}
